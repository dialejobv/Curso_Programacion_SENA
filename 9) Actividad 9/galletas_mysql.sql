-- Base de datos de la panadería: Laboratorio de galletas
DROP DATABASE IF EXISTS panaderia;
CREATE DATABASE panaderia CHARACTER SET utf8mb4;
USE panaderia;

CREATE TABLE ingredientes (
  id INTEGER PRIMARY KEY,
  nombre VARCHAR(40) NOT NULL,
  cantidad_g INTEGER,
  funcion VARCHAR(120)
);

CREATE TABLE lotes (
  id INTEGER PRIMARY KEY,
  fecha DATE,
  temp_horno INTEGER,
  minutos_horno DECIMAL(4,1),
  gramos_bola INTEGER,
  indice_dorado_prom DECIMAL(4,2)
);

CREATE TABLE inspecciones (
  id INTEGER PRIMARY KEY AUTO_INCREMENT,
  lote_id INTEGER NOT NULL,
  estado_real VARCHAR(10),
  estado_detector VARCHAR(10),
  indice_dorado DECIMAL(4,2),
  FOREIGN KEY (lote_id) REFERENCES lotes(id)
);

CREATE TABLE paquetes (
  id INTEGER PRIMARY KEY AUTO_INCREMENT,
  lote_id INTEGER NOT NULL,
  num_galletas INTEGER,
  sellado INTEGER,
  quemadas INTEGER,
  aprobado INTEGER,
  FOREIGN KEY (lote_id) REFERENCES lotes(id)
);

CREATE TABLE carros (
  id INTEGER PRIMARY KEY,
  placa VARCHAR(10) NOT NULL,
  conductor VARCHAR(40),
  capacidad_canastas INTEGER
);

CREATE TABLE tiendas (
  id INTEGER PRIMARY KEY AUTO_INCREMENT,
  nombre VARCHAR(60) NOT NULL,
  barrio VARCHAR(40),
  localidad VARCHAR(40)
);

CREATE TABLE canastas (
  id INTEGER PRIMARY KEY AUTO_INCREMENT,
  carro_id INTEGER NOT NULL,
  num_paquetes INTEGER,
  fecha DATE,
  FOREIGN KEY (carro_id) REFERENCES carros(id)
);

CREATE TABLE entregas (
  id INTEGER PRIMARY KEY AUTO_INCREMENT,
  carro_id INTEGER NOT NULL,
  tienda_id INTEGER NOT NULL,
  fecha DATE,
  canastas INTEGER,
  FOREIGN KEY (carro_id) REFERENCES carros(id),
  FOREIGN KEY (tienda_id) REFERENCES tiendas(id)
);

